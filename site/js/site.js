  /* ---------- selection ---------- */
  function findRecord(list, key) {
    if (!key) return null;
    return list.find((r) => r.id === key) || list.find((r) => String(r.platform) === String(key)) || null;
  }
  function syntheticRecord(kind, key) {
    const m = String(key).match(/^(\d+)([a-z])?$/i);
    if (!m) return null;
    const pf = m[1], section = m[2] ? m[2].toLowerCase() : null;
    const p = (S.data.platforms || []).find((x) => String(x.id) === pf);
    if (!p) return null;
    const sec = section && (p.sections || []).includes(section) ? section : ((p.sections || [])[0] || null);
    return { id: kind + '-' + pf + (sec || ''), platform: pf, section: sec, synthetic: true, in_min: kind === 'arr' ? 0 : null };
  }
  function resolveSelectionFromUrl() {
    const fromKey = qs.get('from'), toKey = qs.get('to');
    S.from = findRecord(S.arrivals, fromKey) || (fromKey ? syntheticRecord('arr', fromKey) : null) || S.arrivals[0] || null;
    S.to = findRecord(S.departures, toKey) || (toKey ? syntheticRecord('dep', toKey) : null) || null;
    if (!S.to) {
      S.to = S.departures.find((d) => !S.from || String(d.platform) !== String(S.from.platform)) || S.departures[0] || null;
    }
    computeRoute();
  }
  function updateUrl() {
    const p = new URLSearchParams(location.search);
    if (S.from) p.set('from', S.from.synthetic ? platformLabel(S.from.platform, S.from.section) : S.from.id); else p.delete('from');
    if (S.to) p.set('to', S.to.synthetic ? platformLabel(S.to.platform, S.to.section) : S.to.id); else p.delete('to');
    history.replaceState(null, '', location.pathname + '?' + p.toString());
  }
  function select(kind, rec) {
    if (kind === 'from') S.from = rec; else S.to = rec;
    computeRoute();
    updateUrl();
    renderAll();
    if (S.mode === 'map') frame('transfer');
  }

  function buildSelectors() {
    const fromSel = $('#sel-from'), toSel = $('#sel-to');
    fromSel.addEventListener('change', () => select('from', findRecord(S.arrivals, fromSel.value) || syntheticRecord('arr', fromSel.value)));
    toSel.addEventListener('change', () => select('to', findRecord(S.departures, toSel.value) || syntheticRecord('dep', toSel.value)));
  }
  function fillSelectors() {
    const fromSel = $('#sel-from'), toSel = $('#sel-to');
    fromSel.innerHTML = ''; toSel.innerHTML = '';
    const pfWord = t('dep.platform');
    const addSynthetic = (sel, current) => {
      if (current && current.synthetic) sel.appendChild(el('option', { value: platformLabel(current.platform, current.section), text: pfWord + ' ' + platformLabel(current.platform, current.section) }));
    };
    S.arrivals.forEach((r) => {
      const label = pfWord + ' ' + platformLabel(r.platform, r.section) + ' · ' + trainName(r) + (r.origin ? ' ' + t('train.from', { x: r.origin }) : '');
      fromSel.appendChild(el('option', { value: r.id, text: label }));
    });
    addSynthetic(fromSel, S.from);
    (S.data.platforms || []).forEach((p) => {
      (p.sections && p.sections.length ? p.sections : [null]).forEach((sec) => {
        const key = platformLabel(p.id, sec);
        if (S.arrivals.some((r) => String(r.platform) === String(p.id) && (r.section || null) === sec)) return;
        if (S.from && S.from.synthetic && platformLabel(S.from.platform, S.from.section) === key) return;
        fromSel.appendChild(el('option', { value: key, text: pfWord + ' ' + key }));
      });
    });
    S.departures.forEach((r) => {
      const label = pfWord + ' ' + platformLabel(r.platform, r.section) + ' · ' + trainName(r) + (r.destination ? ' ' + t('train.to', { x: r.destination }) : '') + ' · ' + whenText(r);
      toSel.appendChild(el('option', { value: r.id, text: label }));
    });
    addSynthetic(toSel, S.to);
    (S.data.platforms || []).forEach((p) => {
      (p.sections && p.sections.length ? p.sections : [null]).forEach((sec) => {
        const key = platformLabel(p.id, sec);
        if (S.departures.some((r) => String(r.platform) === String(p.id) && (r.section || null) === sec)) return;
        if (S.to && S.to.synthetic && platformLabel(S.to.platform, S.to.section) === key) return;
        toSel.appendChild(el('option', { value: key, text: pfWord + ' ' + key }));
      });
    });
    if (S.from) fromSel.value = S.from.synthetic ? platformLabel(S.from.platform, S.from.section) : S.from.id;
    if (S.to) toSel.value = S.to.synthetic ? platformLabel(S.to.platform, S.to.section) : S.to.id;
  }

  /* ---------- time ---------- */
  function elapsedMin() { return (Date.now() - S.loadTime) / 60000; }
  function remainingMin(rec) {
    if (rec == null || rec.in_min == null) return null;
    return rec.in_min + (rec.delay_min || 0) - elapsedMin();
  }
  function clockText(rec) {
    if (rec.in_min == null) return '';
    return fmtTime(new Date(S.loadTime + (rec.in_min + (rec.delay_min || 0)) * 60000));
  }
  function whenText(rec) {
    const rem = remainingMin(rec);
    if (rem == null) return '';
    if (rem < -0.5) return t('dep.gone');
    if (rem < 0.5) return t('dep.now');
    return t('dep.min', { n: Math.round(rem) });
  }

  /* ---------- route ---------- */
  function platformNodeId(rec) {
    if (!rec) return null;
    const p = (S.data.platforms || []).find((x) => String(x.id) === String(rec.platform));
    if (!p) return null;
    const sec = rec.section && (p.sections || []).includes(rec.section) ? rec.section : ((p.sections || [])[0] || '');
    return 'p' + p.id + sec;
  }
  function computeRoute() {
    S.route = null;
    const a = platformNodeId(S.from), b = platformNodeId(S.to);
    if (!a || !b || !S.nodes[a] || !S.nodes[b]) return;
    if (a === b) { S.route = { nodes: [a], edges: [], seconds: 0, same: true }; return; }
    if (String(S.from.platform) === String(S.to.platform) && S.nodes[a] && S.nodes[b]) {
      /* same platform, other section: still run the search so the walk along the platform is shown */
    }
    const adj = {};
    (S.data.edges || []).forEach((e) => {
      if (!S.nodes[e.from] || !S.nodes[e.to]) return;
      (adj[e.from] = adj[e.from] || []).push({ to: e.to, edge: e });
      (adj[e.to] = adj[e.to] || []).push({ to: e.from, edge: e });
    });
    const dist = { [a]: 0 }, prev = {}, prevEdge = {}, done = {};
    const pending = new Set([a]);
    while (pending.size) {
      let u = null;
      pending.forEach((k) => { if (u === null || dist[k] < dist[u]) u = k; });
      pending.delete(u); done[u] = true;
      if (u === b) break;
      (adj[u] || []).forEach(({ to, edge }) => {
        if (done[to]) return;
        const nd = dist[u] + (Number(edge.seconds) || 0);
        if (dist[to] == null || nd < dist[to]) { dist[to] = nd; prev[to] = u; prevEdge[to] = edge; pending.add(to); }
      });
    }
    if (dist[b] == null) return;
    const nodes = [b], edges = [];
    let cur = b;
    while (cur !== a) { edges.unshift(prevEdge[cur]); cur = prev[cur]; nodes.unshift(cur); }
    S.route = { nodes, edges, seconds: dist[b], same: false };
  }

  function buildSteps() {
    const route = S.route;
    const steps = [];
    if (!route) return steps;
    const from = S.from, to = S.to;
    steps.push({ key: 'start', text: t('step.getOff', { pf: platformLabel(from.platform, from.section) }), node: route.nodes[0] });
    if (route.same) {
      steps.push({ key: 'end', text: t('transfer.same'), node: route.nodes[0] });
      return steps;
    }
    let carry = 0;
    for (let i = 0; i < route.edges.length; i++) {
      const u = S.nodes[route.nodes[i]], v = S.nodes[route.nodes[i + 1]], e = route.edges[i];
      carry += Number(e.seconds) || 0;
      if (v.kind === 'waypoint') continue;
      const isLast = i === route.edges.length - 1;
      const lu = S.levelPos[u.level] || 0, lv = S.levelPos[v.level] || 0;
      const label = nodeLabel(v);
      let text;
      const kind = String(e.kind || 'walk');
      if (kind === 'walk' || lu === lv) {
        if (v.kind === 'hall' || v.kind === 'passage') text = t('step.walkThrough', { x: label });
        else if (u.kind === 'platform' && v.kind !== 'platform') text = t('step.walkAlong', { x: label });
        else text = t('step.walkTo', { x: label });
      } else {
        const up = lv > lu;
        const map = { stairs: up ? 'step.stairsUp' : 'step.stairsDown', escalator: up ? 'step.escUp' : 'step.escDown', lift: up ? 'step.liftUp' : 'step.liftDown', ramp: up ? 'step.rampUp' : 'step.rampDown' };
        // when you arrive by stairs, name the place you arrive at (the "short" label), not the stairs themselves
        text = t(map[kind] || (up ? 'step.stairsUp' : 'step.stairsDown'), { x: v.short ? pick(v.short) : label });
      }
      const last = steps[steps.length - 1];
      if (last && last.key === 'step' && last.text === text) {
        // the same instruction twice in a row (for example two nodes inside one tunnel): merge
        last.seconds += carry; last.node = v.id; last.isLast = isLast;
        last.sub = durationText(last.seconds);
        carry = 0;
        continue;
      }
      steps.push({ key: 'step', text, sub: durationText(carry), seconds: carry, node: v.id, isLast });
      carry = 0;
    }
    const endText = t('step.arrive', { pf: platformLabel(to.platform, to.section) });
    const ends = S.data.ends || {};
    const towards = to.to_end && ends[to.to_end] ? t('step.arriveTowards', { x: pick(ends[to.to_end].towards) }) : null;
    steps.push({ key: 'end', text: endText, sub: towards, node: route.nodes[route.nodes.length - 1] });
    return steps;
  }
  function durationText(seconds) {
    return seconds >= 90 ? t('step.minutes', { m: Math.round(seconds / 60) }) : t('step.seconds', { s: Math.round(seconds / 5) * 5 });
  }
  function nodeLabel(n) {
    if (n.label) return pick(n.label);
    if (n.kind === 'platform') return t('dep.platform').toLowerCase() + ' ' + platformLabel(n.platform, n.section);
    return n.id;
  }

  function drawRoute(steps) {
    const layer = S.svg.querySelector('#layer-route');
    layer.innerHTML = '';
    const route = S.route;
    if (!route || route.same) return;
    const pts = route.nodes.map((id) => S.nodes[id]).filter((n) => !isNaN(n.x));
    if (pts.length < 2) return;
    const dAll = 'M ' + pts.map((p) => p.x.toFixed(2) + ' ' + p.y.toFixed(2)).join(' L ');
    layer.appendChild(svgEl('path', { class: 'route-casing', d: dAll }));
    for (let i = 0; i < route.nodes.length - 1; i++) {
      const u = S.nodes[route.nodes[i]], v = S.nodes[route.nodes[i + 1]];
      if (isNaN(u.x) || isNaN(v.x)) continue;
      const passage = (S.levelPos[u.level] || 0) !== 0 || (S.levelPos[v.level] || 0) !== 0;
      layer.appendChild(svgEl('path', { class: 'route-line' + (passage ? ' is-passage' : ''), d: 'M ' + u.x + ' ' + u.y + ' L ' + v.x + ' ' + v.y }));
    }
    let n = 0;
    steps.forEach((st) => {
      const node = S.nodes[st.node]; if (!node || isNaN(node.x)) return;
      if (st.key === 'start') { layer.appendChild(svgEl('circle', { class: 'route-start', cx: node.x, cy: node.y, r: 2.6 })); return; }
      if (st.key === 'end') { layer.appendChild(svgEl('circle', { class: 'route-end', cx: node.x, cy: node.y, r: 2.6 })); return; }
      n += 1;
      if (st.isLast) return; // the last step lands on the destination platform: the end marker is enough
      layer.appendChild(svgEl('circle', { class: 'route-step-bg', cx: node.x, cy: node.y, r: 3 }));
      layer.appendChild(svgEl('text', { class: 'route-step-text', x: node.x, y: node.y + 1.4 }, [String(n + 1)]));
    });
  }

