/* Perronjoy — shared script for index.html and station.html.
   Station builders do not edit this file. It reads one station folder
   (station.json + scene.svg) and does everything else: shadows, track art,
   platform badges, people, trains, the walking route, the transfer verdict,
   camera framing, list mode, languages and the clock.
   Contract for station files: docs/SPEC.md

   Performance notes
   - One shared requestAnimationFrame loop drives every animation (ticker).
   - Track positions come from a lookup table built once per track, so a
     moving train never calls getPointAtLength() during a frame.
   - CSS animations only change opacity, transform or a dash offset. */

