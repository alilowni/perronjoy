  function transferBox() {
    const boxes = [];
    if (S.from && S.platformBoxes[String(S.from.platform)]) boxes.push(S.platformBoxes[String(S.from.platform)]);
    if (S.to && S.platformBoxes[String(S.to.platform)]) boxes.push(S.platformBoxes[String(S.to.platform)]);
    let x1 = Infinity, y1 = Infinity, x2 = -Infinity, y2 = -Infinity;
    if (S.route) S.route.nodes.forEach((id) => { const n = S.nodes[id]; if (n && !isNaN(n.x)) { x1 = Math.min(x1, n.x - 6); y1 = Math.min(y1, n.y - 6); x2 = Math.max(x2, n.x + 6); y2 = Math.max(y2, n.y + 6); } });
    if (isFinite(x1)) {
      // Platforms are long: include their width, but only the part near the route.
      boxes.forEach((b) => { x1 = Math.min(x1, b.x); x2 = Math.max(x2, b.x + b.width); });
      const padY = Math.max(50, (y2 - y1) * 0.35);
      y1 -= padY; y2 += padY;
    } else {
      boxes.forEach((b) => { x1 = Math.min(x1, b.x); y1 = Math.min(y1, b.y); x2 = Math.max(x2, b.x + b.width); y2 = Math.max(y2, b.y + b.height); });
    }
    if (!isFinite(x1)) return null;
    return { x: x1, y: y1, width: x2 - x1, height: y2 - y1 };
  }
  function fitToAspect(box) {
    const mapWrap = $('#map');
    const W = mapWrap.clientWidth || 390, H = mapWrap.clientHeight || 600;
    const A = W / H;
    let { x, y, width, height } = box;
    const padX = width * 0.1 + 6, padY = height * 0.12 + 10;
    x -= padX; width += padX * 2; y -= padY; height += padY * 2;
    const minH = 150, minW = 110;
    if (height < minH) { y -= (minH - height) / 2; height = minH; }
    if (width < minW) { x -= (minW - width) / 2; width = minW; }
    if (width / height < A) { const nw = height * A; x -= (nw - width) / 2; width = nw; }
    else { const nh = width / A; y -= (nh - height) / 2; height = nh; }
    return { x, y, width, height };
  }
