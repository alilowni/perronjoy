/* Perronjoy — shared script for index.html and station.html.
   Station builders do not edit this file. It reads a station folder
   (station.json + scene.svg) and does everything else:
   track art, platform badges, people, trains, the walking route,
   the transfer verdict, framing, list mode and the clock.
   See SPEC.md for the contract the station files must follow. */

