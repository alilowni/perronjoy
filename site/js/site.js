  /* ---------- one animation loop for everything ---------- */
  const ticker = (() => {
    const tasks = new Set();
    let running = false;
    function loop(now) {
      tasks.forEach((task) => { if (task(now) === false) tasks.delete(task); });
      if (tasks.size) requestAnimationFrame(loop); else running = false;
    }
    return {
      add(task) { tasks.add(task); if (!running) { running = true; requestAnimationFrame(loop); } return () => tasks.delete(task); }
    };
  })();
  /* tween(ms, ease, update(k), done) → cancel() */
  function tween(duration, ease, update, done) {
    const t0 = performance.now();
    let live = true;
    const remove = ticker.add((now) => {
      if (!live) return false;
      const k = Math.min(1, (now - t0) / duration);
      update(ease(k));
      if (k >= 1) { live = false; if (done) done(); return false; }
      return true;
    });
    return () => { live = false; remove(); };
  }

