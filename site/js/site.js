  /* ---------- framing (viewBox) ---------- */
  function currentViewBox() {
    const vb = S.svg.getAttribute('viewBox').split(/[\s,]+/).map(Number);
    return { x: vb[0], y: vb[1], width: vb[2], height: vb[3] };
  }
  function transferBox() {
    const boxes = [];
    const pushBox = (b) => { if (b) boxes.push(b); };
    if (S.from) pushBox(S.platformBoxes[String(S.from.platform)]);
    if (S.to) pushBox(S.platformBoxes[String(S.to.platform)]);
    let x1 = Infinity, y1 = Infinity, x2 = -Infinity, y2 = -Infinity;
    if (S.route) S.route.nodes.forEach((id) => { const n = S.nodes[id]; if (n && !isNaN(n.x)) { x1 = Math.min(x1, n.x - 6); y1 = Math.min(y1, n.y - 6); x2 = Math.max(x2, n.x + 6); y2 = Math.max(y2, n.y + 6); } });
    // platforms are long: include only the part of each platform near the route, plus a margin
    if (isFinite(x1)) {
      boxes.forEach((b) => { x1 = Math.min(x1, b.x); x2 = Math.max(x2, b.x + b.width); });
      const spanY = y2 - y1;
      const padY = Math.max(50, spanY * 0.35);
      y1 -= padY; y2 += padY;
    } else {
      boxes.forEach((b) => { x1 = Math.min(x1, b.x); y1 = Math.min(y1, b.y); x2 = Math.max(x2, b.x + b.width); y2 = Math.max(y2, b.y + b.height); });
    }
    if (!isFinite(x1)) return null;
    return { x: x1, y: y1, width: x2 - x1, height: y2 - y1 };
  }
  function fitToAspect(box) {
    const mapWrap = $('#map');
    const W = mapWrap.clientWidth || 390, H = mapWrap.clientHeight || 600;
    const A = W / H;
    let { x, y, width, height } = box;
    const padX = width * 0.1 + 6, padY = height * 0.12 + 10;
    x -= padX; width += padX * 2; y -= padY; height += padY * 2;
    const minH = 150, minW = 110;
    if (height < minH) { y -= (minH - height) / 2; height = minH; }
    if (width < minW) { x -= (minW - width) / 2; width = minW; }
    if (width / height < A) { const nw = height * A; x -= (nw - width) / 2; width = nw; }
    else { const nh = width / A; y -= (nh - height) / 2; height = nh; }
    return { x, y, width, height };
  }
  function frame(mode, instant) {
    if (!S.svg) return;
    S.frameMode = mode;
    updateFrameButton();
    let target = null;
    if (mode === 'transfer') { const b = transferBox(); if (b) target = fitToAspect(b); }
    if (!target) target = fitToAspect(S.fullViewBox);
    setViewBox(target, instant || MOTION_OFF);
  }
  function setViewBox(target, instant) {
    const svg = S.svg;
    const apply = (vb) => svg.setAttribute('viewBox', [vb.x, vb.y, vb.width, vb.height].map((n) => n.toFixed(2)).join(' '));
    if (S.viewAnim) { cancelAnimationFrame(S.viewAnim); S.viewAnim = null; }
    if (instant) { apply(target); return; }
    const start = currentViewBox(), t0 = performance.now(), dur = 850;
    const step = (now) => {
      const k = easeInOutCubic(Math.min(1, (now - t0) / dur));
      apply({ x: start.x + (target.x - start.x) * k, y: start.y + (target.y - start.y) * k, width: start.width + (target.width - start.width) * k, height: start.height + (target.height - start.height) * k });
      if (k < 1) S.viewAnim = requestAnimationFrame(step); else S.viewAnim = null;
    };
    S.viewAnim = requestAnimationFrame(step);
  }

  /* ---------- trains ---------- */
  function stopPosition(rec) {
    const track = S.tracks[String(rec.platform)];
    if (!track) return null;
    const nodeId = platformNodeId(rec);
    const node = nodeId ? S.nodes[nodeId] : null;
    if (node && !isNaN(node.x)) return track.project(node.x, node.y);
    return track.len / 2;
  }
  function makeTrain(rec, kind) {
    const track = S.tracks[String(rec.platform)];
    if (!track) return null;
    const length = Number(rec.length_m) || DEFAULT_TRAIN_LENGTH;
    const cars = Math.max(2, Math.round(length / CAR_LENGTH));
    const g = svgEl('g', { class: 'train train--' + trainCategory(rec.train), 'data-record': rec.id });
    const carEls = [];
    const carLen = CAR_LENGTH - CAR_GAP;
    for (let i = 0; i < cars; i++) {
      const car = svgEl('g', { class: 'car' });
      car.appendChild(svgEl('rect', { class: 'train-shadow', x: -CAR_WIDTH / 2 + 0.6, y: -carLen / 2 + 0.6, width: CAR_WIDTH, height: carLen, rx: 1.6 }));
      car.appendChild(svgEl('rect', { class: 'train-car', x: -CAR_WIDTH / 2, y: -carLen / 2, width: CAR_WIDTH, height: carLen, rx: 1.6 }));
      car.appendChild(svgEl('rect', { class: 'train-glass', x: -CAR_WIDTH / 2 + 1.5, y: -carLen / 2 + 3, width: CAR_WIDTH - 3, height: carLen - 6, rx: 0.8 }));
      if (i === 0) car.appendChild(svgEl('path', { class: 'train-nose', d: noseD(carLen, +1) }));
      if (i === cars - 1) car.appendChild(svgEl('path', { class: 'train-nose', d: noseD(carLen, -1) }));
      g.appendChild(car); carEls.push(car);
    }
    S.svg.querySelector('#layer-trains').appendChild(g);
    const train = { rec, kind, track, g, carEls, cars, length: cars * CAR_LENGTH, s: 0, dir: 1, anim: null, gone: false };
    S.trains[rec.id] = train;
    return train;
  }
  function noseD(carLen, sign) {
    // a rounded cab band at the +y (sign=1) or -y (sign=-1) end of a car, local coordinates
    const w = CAR_WIDTH / 2, y0 = sign * (carLen / 2), y1 = sign * (carLen / 2 - 4.5);
    return ['M', -w + 0.3, y1, 'L', w - 0.3, y1, 'L', w - 0.3, y0 - sign * 1.6, 'Q', w - 0.3, y0, w - 1.9, y0, 'L', -w + 1.9, y0, 'Q', -w + 0.3, y0, -w + 0.3, y0 - sign * 1.6, 'Z'].join(' ');
  }
  function placeTrain(train, s, dir) {
    train.s = s; train.dir = dir;
    const pitch = CAR_LENGTH;
    train.carEls.forEach((car, i) => {
      const si = s + dir * (((train.cars - 1) / 2) - i) * pitch;
      const p = train.track.pointAt(si), tg = train.track.tangentAt(si);
      const hx = tg.x * dir, hy = tg.y * dir;
      const angle = Math.atan2(hy, hx) * 180 / Math.PI - 90;
      car.setAttribute('transform', 'translate(' + p.x.toFixed(2) + ' ' + p.y.toFixed(2) + ') rotate(' + angle.toFixed(2) + ')');
    });
  }
  function dirTowards(end) { return end === 'top' ? -1 : 1; }
  function animateTrain(train, from, to, dir, duration, ease, done) {
    if (train.anim) cancelAnimationFrame(train.anim);
    if (MOTION_OFF || duration <= 0) { placeTrain(train, to, dir); if (done) done(); return; }
    const t0 = performance.now();
    const step = (now) => {
      const k = ease(Math.min(1, (now - t0) / duration));
      placeTrain(train, from + (to - from) * k, dir);
      if (k < 1) train.anim = requestAnimationFrame(step); else { train.anim = null; if (done) done(); }
    };
    train.anim = requestAnimationFrame(step);
  }
  function placeStandingTrains() {
    S.departures.forEach((r) => {
      const train = makeTrain(r, 'dep'); if (!train) return;
      const stop = stopPosition(r);
      const rem = remainingMin(r);
      if (rem != null && rem < -0.5) { train.gone = true; train.g.remove(); return; }
      placeTrain(train, stop, dirTowards(r.to_end || 'top'));
    });
  }
  function playArrival() {
    const r = S.from;
    if (!r || r.synthetic || !S.tracks[String(r.platform)]) return;
    const train = makeTrain(r, 'arr'); if (!train) return;
    const stop = stopPosition(r);
    const fromEnd = r.from_end || 'top';
    const dir = fromEnd === 'top' ? 1 : -1;      // enters from the top → travels down the path
    const start = fromEnd === 'top' ? -(train.length / 2 + OFFSCREEN) : train.track.len + train.length / 2 + OFFSCREEN;
    const hasDepartureHere = S.departures.some((d) => String(d.platform) === String(r.platform) && (d.section || null) === (r.section || null) && S.trains[d.id] && !S.trains[d.id].gone);
    if (hasDepartureHere) { train.g.remove(); delete S.trains[r.id]; return; } // the standing train is this train
    animateTrain(train, start, stop, dir, 7000, easeOutCubic);
  }
  function departTrain(train) {
    if (train.gone) return;
    train.gone = true;
    const end = train.rec.to_end || 'top';
    const dir = dirTowards(end);
    const target = end === 'top' ? -(train.length / 2 + OFFSCREEN) : train.track.len + train.length / 2 + OFFSCREEN;
    animateTrain(train, train.s, target, dir, 7000, easeInCubic, () => train.g.remove());
  }

