  /* A track with a lookup table: positions along the path without DOM calls per frame. */
  function makeTrack(pathEl) {
    const len = pathEl.getTotalLength();
    const n = Math.max(2, Math.ceil(len / LUT_STEP));
    const step = len / n;
    const xs = new Float32Array(n + 1), ys = new Float32Array(n + 1);
    for (let i = 0; i <= n; i++) { const q = pathEl.getPointAtLength(i * step); xs[i] = q.x; ys[i] = q.y; }
    const unit = (dx, dy) => { const l = Math.hypot(dx, dy) || 1; return { x: dx / l, y: dy / l }; };
    const t0 = unit(xs[1] - xs[0], ys[1] - ys[0]);
    const tL = unit(xs[n] - xs[n - 1], ys[n] - ys[n - 1]);
    function pointAt(s) {
      if (s <= 0) return { x: xs[0] + t0.x * s, y: ys[0] + t0.y * s };
      if (s >= len) return { x: xs[n] + tL.x * (s - len), y: ys[n] + tL.y * (s - len) };
      const f = s / step, i = Math.floor(f), r = f - i;
      return { x: xs[i] + (xs[i + 1] - xs[i]) * r, y: ys[i] + (ys[i + 1] - ys[i]) * r };
    }
    function tangentAt(s) {
      if (s <= 0) return t0;
      if (s >= len) return tL;
      const i = Math.min(n - 1, Math.floor(s / step));
      return unit(xs[i + 1] - xs[i], ys[i + 1] - ys[i]);
    }
    function project(x, y) {
      let best = 0, bd = Infinity;
      for (let i = 0; i <= n; i++) { const d = (xs[i] - x) ** 2 + (ys[i] - y) ** 2; if (d < bd) { bd = d; best = i; } }
      return best * step;
    }
    return { el: pathEl, len, pointAt, tangentAt, project };
  }

  function readNodes() {
    const svg = S.svg;
    (S.data.nodes || []).forEach((n) => {
      const c = svg.querySelector('#node-' + cssId(n.id));
      const node = Object.assign({}, n);
      if (c) { node.x = parseFloat(c.getAttribute('cx')); node.y = parseFloat(c.getAttribute('cy')); }
      else { node.x = NaN; node.y = NaN; node.missing = true; }
      if (!node.level) node.level = 'platform';
      S.nodes[n.id] = node;
      if (node.kind === 'toilet') S.toiletIds.push(n.id);
    });
    (S.data.platforms || []).forEach((p) => {
      const r = svg.querySelector('#platform-' + cssId(p.id));
      if (r && r.getBBox) { const b = r.getBBox(); S.platformBoxes[p.id] = { x: b.x, y: b.y, width: b.width, height: b.height }; }
    });
  }

