/* Perronjoy — boot script, loaded in <head> before the page paints.
   It sets the theme and the language attribute early, so there is no flash
   of the wrong theme. Station builders do not edit this file.

   Theme order: ?theme=light|dark (not stored) → stored choice → system setting.
   Motion: ?motion=off or the system "reduce motion" setting. */

(function () {
  'use strict';
  var root = document.documentElement;
  var qs = new URLSearchParams(location.search);
  var THEME_KEY = 'perronjoy.theme';
  var LANG_KEY = 'perronjoy.lang';
  var mq = window.matchMedia ? window.matchMedia('(prefers-color-scheme: dark)') : null;
  var reduce = window.matchMedia && window.matchMedia('(prefers-reduced-motion: reduce)').matches;

  function read(key) { try { return localStorage.getItem(key); } catch (e) { return null; } }
  function write(key, value) { try { localStorage.setItem(key, value); } catch (e) { /* private mode */ } }

  var forced = qs.get('theme');
  function resolve() {
    if (forced === 'light' || forced === 'dark') return forced;
    var s = read(THEME_KEY);
    if (s === 'light' || s === 'dark') return s;
    return mq && mq.matches ? 'dark' : 'light';
  }
  function apply(theme) {
    root.dataset.theme = theme;
    var meta = document.querySelector('meta[name="theme-color"]');
    if (meta) meta.setAttribute('content', theme === 'dark' ? '#0e1318' : '#f2f4f7');
  }
  apply(resolve());
  if (mq && mq.addEventListener) mq.addEventListener('change', function () { if (!read(THEME_KEY) && !forced) apply(resolve()); });

  var lang = qs.get('lang') || read(LANG_KEY);
  root.lang = lang === 'en' ? 'en' : 'nl';
  if (qs.get('motion') === 'off' || reduce) root.dataset.motion = 'off';

  function toggle() {
    var next = root.dataset.theme === 'dark' ? 'light' : 'dark';
    forced = null;
    write(THEME_KEY, next);
    var done = function () { apply(next); document.dispatchEvent(new CustomEvent('perronjoy:theme', { detail: { theme: next } })); };
    // A view transition cross-fades the whole page on the GPU: one smooth fade, no repaint flicker.
    if (document.startViewTransition && root.dataset.motion !== 'off') document.startViewTransition(done);
    else done();
  }

  window.PerronjoyTheme = { toggle: toggle, get theme() { return root.dataset.theme; } };
  document.addEventListener('DOMContentLoaded', function () {
    document.querySelectorAll('.theme-switch').forEach(function (b) { b.addEventListener('click', toggle); });
  });
})();
